# ============================================================================
# 角色 → 默认提示词映射
# ============================================================================

ROLE_PROMPTS: dict[str, dict[str, str]] = {
    "architect": {"system": ARCHITECT_PROMPT, "task_prefix": "请根据以下任务进行架构设计："},
    "developer": {"system": DEVELOPER_PROMPT, "task_prefix": "请完成以下开发任务："},
    "tester": {"system": TESTER_PROMPT, "task_prefix": "请为以下内容设计测试方案："},
    "reviewer": {"system": REVIEWER_PROMPT, "task_prefix": "请审查以下内容："},
    "deployer": {"system": DEPLOYER_PROMPT, "task_prefix": "请完成以下部署任务："},
}


def get_role_prompt(role: str) -> dict[str, str]:
    """获取指定角色的默认提示词。

    Returns:
        {"system": str, "task_prefix": str} 或 Developer 的默认值
    """
    return ROLE_PROMPTS.get(
        role,
        ROLE_PROMPTS["developer"],  # 未知角色回退到 developer
    )


def get_effective_prompt(role: str, custom_system_prompt: str | None) -> str:
    """获取 Agent 实际使用的系统提示词。

    优先级：自定义 system_prompt > 角色默认提示词

    Args:
        role: 角色名 (architect/developer/tester/reviewer/deployer)
        custom_system_prompt: Agent 的自定义 system_prompt（可为 None 或空字符串）

    Returns:
        最终使用的系统提示词
    """
    if custom_system_prompt and custom_system_prompt.strip():
        return custom_system_prompt.strip()
    return get_role_prompt(role)["system"]
